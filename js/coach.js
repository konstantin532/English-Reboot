/* ==========================================================================
   English Reboot — Этап 6: голос коуча в одном файле
   Файл: coach.js — все реплики коуча (лестница, ловушки, «Сегодня», сцены,
   импровизация) и выбор реплики дня по фактам.
   ПРАВИЛО ЧЕСТНОСТИ: хвалим только то, что проверено (точное совпадение,
   проверка по смыслу, распознавание речи от 80). Реплики, которые звучат без
   проверки (самооценка, ошибка, «не удалось проверить»), перечислены в
   UNCHECKED — в них нет слов похвалы, это проверяет тест.
   Сравниваем ученика только с ним самим (вчера, лучший день) — не с другими.
   ========================================================================== */

const Coach = (() => {
  'use strict';

  const LINES = {
    ladder: {
      ok: ['Точно!', 'Есть!', 'Вот это по-американски.', 'Чисто.', 'Да, именно так.'], // проверено автоматически
      typo: ['Засчитано — только глянь на опечатку.', 'Засчитано, одна буква сбежала.'],
      self: ['Отмечено по твоей оценке. FSRS вернёт фразу вовремя.', 'Принято: «звучит похоже». Повторение покажет, закрепилось ли.'],
      miss: ['Не беда — запоминаем и едем дальше.', 'Мимо, но это и есть тренировка.', 'Ошибка — это нормально. Вот как говорят:'],
      selfMiss: ['Честная оценка — фраза вернётся пораньше.', 'Отмечено: пока не очень. Вернёмся к ней скоро.'],
      up: ['Новая ступень открыта.', 'Шаг вверх.'],
      down: ['Шаг назад, чтобы закрепить.', 'Вернёмся на ступеньку — так надёжнее.'],
      top: ['Фраза пройдена по всей лестнице.'],
    },
    traps: { // ответ проверяется автоматически: какое слово прозвучало
      ok: ['Слышишь разницу!', 'Точно!', 'Ухо уже американское.', 'Есть!'],
      miss: ['Коварная пара — послушай ещё раз обе.', 'Сравни медленно ещё раз.', 'Это и есть ловушка — теперь ты её знаешь.'],
    },
    today: {
      fresh: 'Пятнадцать минут — и сегодня ты скажешь по-английски больше, чем вчера.',
      resume: 'Урок на паузе — продолжим с того же места.',
      done: 'Урок дня пройден. Хочешь — ещё один, хочешь — загляни в библиотеку.',
      empty: 'Всё повторено и все фразы в работе. FSRS вернёт их, когда придёт время.',
    },
    scenes: {
      matched: 'Засчитано',
      unknown: 'Автоматически проверить не получилось — это не значит, что ответ плохой. Сравни с образцами:',
      voiceOnly: 'Голосовой ответ без распознавания речи автоматически не проверить. Сравни с образцами:',
      done: 'Эпизод пройден.',
    },
    improv: {
      think: 'Подумай пару секунд — не над грамматикой, а над тем, ЧТО сказать.',
      talk: 'Говори! Ошибки — нормально, главное не молчать.',
      condOk: 'Условие выполнено',
      condMiss: 'Фразы-условия в тексте не нашлось — в следующий раз вверни её.',
      voiceOnly: 'Ответ голосом без распознавания речи автоматически не проверить — сравни с образцами.',
    },
    // Реплика дня — только по фактам «Сказано вслух»; {n}, {m}, {d} подставляются
    day: {
      zero: 'Сегодня вслух пока ничего. Одна фраза уже меняет счёт.',
      first: 'Первый день: {n} вслух. Отсчёт пошёл.',
      back: 'С возвращением — перерыв {d}. Сегодня {n} вслух, дальше будет легче.',
      record: 'Рекорд: {n} вслух за день — больше, чем в любой день раньше.',
      more: 'Сегодня {n} вслух — на {m} больше, чем вчера.',
      steady: 'Сегодня {n} вслух, вчера было {m}. Ровный темп тоже работает — главное не пропадать.',
    },
    league: {
      hint: 'Соперники — боты-пейсеры, не люди. Каждый набирает ровно свою норму фраз в день (сегодняшняя норма уже учтена). Лига считает только фразы, сказанные вслух.',
      ahead: 'Ты впереди темпа «{p}» на {n}.',
      even: 'Ты идёшь ровно в темпе «{p}».',
      behind: 'До темпа «{p}» на этой неделе не хватает {n}.',
    },
  };

  // Реплики, которые звучат без автоматической проверки успеха: никакой похвалы
  const UNCHECKED = [
    ['ladder', 'self'], ['ladder', 'miss'], ['ladder', 'selfMiss'], ['ladder', 'down'],
    ['traps', 'miss'], ['scenes', 'unknown'], ['scenes', 'voiceOnly'],
    ['improv', 'condMiss'], ['improv', 'voiceOnly'],
    ['day', 'zero'], ['day', 'steady'], ['league', 'behind'], ['league', 'hint'],
  ];

  const rnd = (arr) => arr[Math.floor(Math.random() * arr.length)];

  // Реплика: строка или случайная из списка
  function line(section, key) {
    const v = LINES[section] && LINES[section][key];
    if (v === undefined) return '';
    return Array.isArray(v) ? rnd(v) : v;
  }

  function fmt(tpl, vars) {
    return String(tpl).replace(/\{(\w+)\}/g, (_, k) => (vars && vars[k] !== undefined ? vars[k] : ''));
  }

  const phrases = (n) => {
    const a = Math.abs(n) % 100, b = a % 10;
    const w = a > 10 && a < 20 ? 'фраз' : b === 1 ? 'фраза' : b >= 2 && b <= 4 ? 'фразы' : 'фраз';
    return `${n} ${w}`;
  };
  const days = (n) => {
    const a = Math.abs(n) % 100, b = a % 10;
    const w = a > 10 && a < 20 ? 'дней' : b === 1 ? 'день' : b >= 2 && b <= 4 ? 'дня' : 'дней';
    return `${n} ${w}`;
  };

  /**
   * Какая реплика дня подходит под факты.
   * facts: { today, yesterday, bestPrevDay, hadBefore, gapDays }
   *   bestPrevDay — максимум «вслух» за любой прошлый день; hadBefore — был ли хоть один день раньше;
   *   gapDays — сколько дней прошло с прошлого дня с фразами вслух (null — не было).
   * @returns {{ key, text }}
   */
  function dayKey(f) {
    const t = f.today || 0;
    if (t <= 0) return 'zero';
    if (!f.hadBefore) return 'first';
    if (f.gapDays !== null && f.gapDays !== undefined && f.gapDays >= 3) return 'back';
    if (t > (f.bestPrevDay || 0)) return 'record';
    if (f.yesterday > 0 && t > f.yesterday) return 'more';
    return 'steady';
  }

  function dayLine(f) {
    const key = dayKey(f);
    const t = f.today || 0;
    const m = key === 'more' ? t - f.yesterday : f.yesterday || 0;
    return { key, text: fmt(LINES.day[key], { n: phrases(t), m: key === 'more' ? phrases(m) : m, d: days(f.gapDays || 0) }) };
  }

  // Строка про пейсер-ориентир: { name, diff } — diff = я − пейсер
  function paceLine(goal) {
    if (!goal) return '';
    const key = goal.diff > 0 ? 'ahead' : goal.diff === 0 ? 'even' : 'behind';
    return fmt(LINES.league[key], { p: goal.name, n: phrases(Math.abs(goal.diff)) });
  }

  return { LINES, UNCHECKED, line, fmt, phrases, dayKey, dayLine, paceLine };
})();

if (typeof globalThis !== 'undefined') globalThis.Coach = Coach;
