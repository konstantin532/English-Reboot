/* ---------- Экспорт и самопроверка ---------- */
(() => {
  const check = (name, arr, needErrors) => {
    const problems = [];
    arr.forEach((c) => {
      if (!c.payload) { problems.push(c.id + ': нет payload'); return; }
      if (!c.payload.examples || c.payload.examples.length < 2) problems.push(c.id + ': мало примеров');
      const t = c.payload.test || [];
      if (t.length !== 5) problems.push(c.id + `: тестов ${t.length} вместо 5`);
      t.forEach((qq, i) => {
        if (!qq || !Array.isArray(qq.options)) { problems.push(`${c.id} тест${i + 1}: нет options`); return; }
        if (qq.options.length < 2) problems.push(`${c.id} тест${i + 1}: мало вариантов`);
        if (new Set(qq.options).size !== qq.options.length) problems.push(`${c.id} тест${i + 1}: дубли вариантов`);
        if (qq.correct === undefined || qq.correct < 0 || qq.correct >= qq.options.length)
          problems.push(`${c.id} тест${i + 1}: неверный correct`);
      });
      if (needErrors && (!c.payload.errors || c.payload.errors.length < 2)) problems.push(c.id + ': мало ошибок');
    });
    if (problems.length) console.warn(name + ' — проблемы:', problems.slice(0, 20), problems.length > 20 ? `… и ещё ${problems.length - 20}` : '');
  };
  check('PHRASAL_CARDS', PHRASAL_CARDS, true);
  check('COLLOCATION_CARDS', COLLOCATION_CARDS, false);
  check('IDIOM_CARDS', IDIOM_CARDS, false);

  window.PHRASAL_CARDS = PHRASAL_CARDS;
  window.COLLOCATION_CARDS = COLLOCATION_CARDS;
  window.IDIOM_CARDS = IDIOM_CARDS;
  console.log(`content_vocab.js: ${PHRASAL_CARDS.length} фразовых, ${COLLOCATION_CARDS.length} коллокаций, ${IDIOM_CARDS.length} идиом`);
})();

