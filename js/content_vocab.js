// Фразовый глагол: P(front, translation, level, tag, examples[], manualTest)
let _pv = 0;
function P(front, tr, level, tag, exs, mt) {
  const id = 'pv_' + String(++_pv).padStart(3, '0');
  const k0 = idxOf(id);
  const verb = front.split(' ')[0];

  // Примеры: снимаем {}; цель есть НЕ в каждом примере — это нормально
  const targets = [];
  const examples = exs.map((raw) => {
    const m = raw.match(/\{([^}]+)\}/);
    targets.push(m ? m[1] : null);
    const clean = raw.replace(/[{}]/g, '');
    return { text: clean, parts: partsOf(clean), connected: '' };
  });

  // Источники тестов: примеры, где {}-цель реально есть в тексте
  const marked = targets
    .map((t, i) => ({ t, i }))
    .filter((m) => m.t && examples[m.i].text.includes(m.t));

  // Дистракторы: голый глагол / инверсия / gerund (или сам front для небазовых форм)
  const gapDistr = (target) => {
    const tw = target.split(' ');
    return [tw[0], tw.slice(1).join(' ') + ' ' + tw[0], target === front ? ing(tw[0]) : front];
  };

  const gap0 = marked.length ? gapTest(marked[0].t, examples[marked[0].i].text, gapDistr(marked[0].t), k0) : null;
  const last = marked.length > 1 ? marked[marked.length - 1] : null;
  const gap1 = last ? gapTest(last.t, examples[last.i].text, gapDistr(last.t), k0 + 3) : null;

  // Тест на частицу: помеченный пример с целью «verb + одна частица»
  const pm = marked.find((m) => {
    const tw = m.t.split(' ');
    return tw.length === 2 && tw[0] === verb && PARTICLES.includes(tw[1]);
  });
  const particleTest = pm
    ? gapTest(pm.t, examples[pm.i].text,
        rotate(PARTICLES.filter((x) => x !== pm.t.split(' ')[1]), k0).slice(0, 3), k0 + 9)
    : null;

  // Ошибки: пропуск частицы и инверсия — только по примерам с целью
  const errors = [];
  if (marked.length) {
    const m1 = marked[0];
    const w1 = m1.t.split(' ');
    errors.push({
      wrong: examples[m1.i].text.replace(m1.t, w1[0]),
      correct: examples[m1.i].text,
      note: `Фразовый глагол требует частицы «${w1.slice(1).join(' ')}».`,
    });
    const m2 = marked.length > 1 ? marked[marked.length - 1] : m1;
    const w2 = m2.t.split(' ');
    errors.push({
      wrong: examples[m2.i].text.replace(m2.t, w2.slice(1).join(' ') + ' ' + w2[0]),
      correct: examples[m2.i].text,
      note: 'Частица стоит сразу после глагола, не перед ним.',
    });
  }

  const tests = [];
  if (gap0) tests.push(gap0);
  if (gap1) tests.push(gap1);
  if (particleTest) tests.push(particleTest);
  tests.push(manualTest(mt), meaningTest(front, tr, 'pv', k0 + 5));
  // Добор до 5 — гарантированно другими типами вопросов
  if (tests.length < 5) tests.push(Object.assign(mix(front, gapDistr(front), k0 + 9), { q: 'Выберите правильный вариант:' }));
  if (tests.length < 5) tests.push(swapTest(front, tr, 'pv', k0 + 11));

  return { id, type: 'phrasal', level, tags: [tag], audio: true,
    payload: { front, translation: tr, examples, errors, test: tests } };
}

// Коллокация: C(front, translation, level, category, examples[], manualTest)
let _cl = 0;
function C(front, tr, level, category, exs, mt) {
  const id = 'cl_' + String(++_cl).padStart(3, '0');
  const k0 = idxOf(id);
  const targets = [];
  const examples = exs.map((raw) => {
    const m = raw.match(/\{([^}]+)\}/);
    targets.push(m ? m[1] : null);
    const clean = raw.replace(/[{}]/g, '');
    return { text: clean, parts: partsOf(clean), connected: '' };
  });

  // Осмысленны только цели, начинающиеся с глагола из VERB_SUBS или прилагательного из ADJ_POOL
  const goodTarget = (t) => {
    const first = t.split(' ')[0];
    return !!VERB_SUBS[first] || ADJ_POOL.includes(first);
  };
  const marked = targets
    .map((t, i) => ({ t, i }))
    .filter((m) => m.t && goodTarget(m.t) && examples[m.i].text.includes(m.t));

  const subDistr = (target) => {
    const first = target.split(' ')[0];
    return rotate(VERB_SUBS[first] || ADJ_POOL, k0).map((s) => target.replace(first, s));
  };

  const gap0 = marked.length ? gapTest(marked[0].t, examples[marked[0].i].text, subDistr(marked[0].t), k0) : null;
  const last = marked.length > 1 ? marked[marked.length - 1] : null;
  const gap1 = last ? gapTest(last.t, examples[last.i].text, subDistr(last.t), k0 + 3) : null;

  // RU→front с подменённым глаголом/прилагательным
  const frontFirst = front.split(' ')[0];
  const swap = Object.assign(
    mix(front, rotate(VERB_SUBS[frontFirst] || ADJ_POOL, k0).map((s) => front.replace(frontFirst, s)), k0 + 7),
    { q: `Как сказать «${tr}»?` });

  const tests = [];
  if (gap0) tests.push(gap0);
  if (gap1) tests.push(gap1);
  tests.push(swap, manualTest(mt), meaningTest(front, tr, 'cl', k0 + 5));
  if (tests.length < 5) tests.push(Object.assign(mix(front, subDistr(front), k0 + 9), { q: 'Выберите правильный вариант:' }));
  if (tests.length < 5) tests.push(swapTest(front, tr, 'cl', k0 + 11));

  return { id, type: 'collocation', level, tags: [category], audio: true,
    payload: { front, translation: tr, category, examples, test: tests } };
}

// Идиома: I(front, translation, level, context, examples[], manualTest)
let _id = 0;
function I(front, tr, level, context, exs, mt) {
  const id = 'id_' + String(++_id).padStart(3, '0');
  const k0 = idxOf(id);
  const targets = [];
  const examples = exs.map((raw) => {
    const m = raw.match(/\{([^}]+)\}/);
    targets.push(m ? m[1] : null);
    const clean = raw.replace(/[{}]/g, '');
    return { text: clean, parts: partsOf(clean), connected: '' };
  });

  const marked = targets
    .map((t, i) => ({ t, i }))
    .filter((m) => m.t && examples[m.i].text.includes(m.t));

  // Дистракторы: усечение / перестановка / замена артикля (или чужой глагол)
  const idiDistr = (target) => {
    const w = target.split(' ');
    const cut = w.slice(0, -1).join(' ');
    const rev = w[w.length - 1] + ' ' + w.slice(0, -1).join(' ');
    const artIdx = w.findIndex((x) => x === 'a' || x === 'an' || x === 'the');
    const third = artIdx >= 0
      ? w.map((x, i) => (i === artIdx ? (x === 'the' ? 'a' : 'the') : x)).join(' ')
      : ['take', 'make', 'do'][k0 % 3] + ' ' + w.slice(1).join(' ');
    return [cut, rev, third];
  };

  const gap0 = marked.length ? gapTest(marked[0].t, examples[marked[0].i].text, idiDistr(marked[0].t), k0) : null;
  const last = marked.length > 1 ? marked[marked.length - 1] : null;
  const gap1 = last ? gapTest(last.t, examples[last.i].text, idiDistr(last.t), k0 + 3) : null;

  const tests = [];
  if (gap0) tests.push(gap0);
  if (gap1) tests.push(gap1);
  tests.push(manualTest(mt), swapTest(front, tr, 'id', k0 + 5), meaningTest(front, tr, 'id', k0 + 8));
  if (tests.length < 5) tests.push(Object.assign(mix(front, idiDistr(front), k0 + 9), { q: 'Выберите правильный вариант идиомы:' }));

  return { id, type: 'idiom', level, tags: ['идиома'], audio: true,
    payload: { front, translation: tr, context, examples, test: tests } };
}

