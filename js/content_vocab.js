// Тест «Что означает X?» — перевод + переводы соседних карточек, без дублей
function meaningTest(front, tr, kind, k) {
  const pool = TRS[kind];
  const seen = new Set([tr]);
  const distr = [];
  for (const step of [1, 5, 11, 2, 8]) {
    const cand = pool[(pool.length + step) % Math.max(pool.length, 1)];
    if (cand && !seen.has(cand)) { distr.push(cand); seen.add(cand); }
    if (distr.length === 3) break;
  }
  for (const cand of FALLBACK_TRS[kind]) {
    if (!seen.has(cand)) { distr.push(cand); seen.add(cand); }
    if (distr.length === 3) break;
  }
  FRONTS[kind].push(front); TRS[kind].push(tr);
  return Object.assign(mix(tr, distr, k), { q: `Что означает «${front}»?` });
}

// Тест RU→front — front + чужие front, без дублей
function swapTest(front, tr, kind, k) {
  const seen = new Set([front]);
  const distr = [];
  for (const step of [1, 3, 7, 2, 5]) {
    const pool = FRONTS[kind];
    if (!pool.length) break;
    const cand = pool[(pool.length + step) % pool.length];
    if (cand && !seen.has(cand)) { distr.push(cand); seen.add(cand); }
    if (distr.length === 3) break;
  }
  for (const cand of FALLBACK_FRONTS[kind]) {
    if (!seen.has(cand)) { distr.push(cand); seen.add(cand); }
    if (distr.length === 3) break;
  }
  return Object.assign(mix(front, distr, k), { q: `Как сказать «${tr}»?` });
}

