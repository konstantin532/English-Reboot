const POS_MAP = { n:'noun',v:'verb',a:'adj',d:'adv',p:'prep',pr:'pron',c:'conj',r:'art',t:'det',u:'num',x:'aux',m:'modal',q:'part' };
const idxOf = (id) => Number(String(id).replace(/\D/g, '')) || 0;

// parts из строки: каждое слово → {word,pos,ipa,silent,surprise[,stress]}
function partsOf(text) {
  return text.split(/\s+/).filter(Boolean).map((tok) => {
    const bare = tok.toLowerCase().replace(/[^a-z']/g, '').replace(/'s$/, '');
    const r = LEX[bare];
    const rec = r ? r.split('|') : null;
    const p = {
      word: tok,
      pos: rec ? (POS_MAP[rec[1]] || '') : '',
      ipa: rec ? '/' + rec[0] + '/' : '',
      silent: rec && rec[3] ? rec[3].split('').map(Number) : [],
      surprise: rec && rec[4] ? rec[4].split('').map(Number) : [],
    };
    if (rec && rec[2] !== undefined && rec[2] !== '') p.stress = Number(rec[2]);
    return p;
  });
}

// gerund по простым правилам (get→getting, make→making, carry→carrying)
function ing(v) {
  if (/[^aeiou][aeiou]([bdgklmnprt])$/.test(v) && v.length <= 4) return v + v.slice(-1) + 'ing';
  if (/e$/.test(v) && !/ee$/.test(v)) return v.slice(0, -1) + 'ing';
  return v + 'ing';
}

// Поворот пула на k — разнообразие дистракторов между карточками
const rotate = (pool, k) => pool.length ? pool.map((_, i) => pool[(i + k) % pool.length]) : pool;

// Сборка варианта: правильный вставляется на позицию k%4 (детерминированный разброс)
function mix(correct, distr, k) {
  const opts = distr.filter((d) => d && d !== correct).slice(0, 3);
  const pos = ((k % 4) + 4) % 4;
  opts.splice(pos, 0, correct);
  return { q: '', options: opts, correct: pos };
}

// Разбор ручного теста 'q|o|o|o|o|i'
function manualTest(str) {
  const p = str.split('|');
  return { q: p[0].replace('_', '___'), options: p.slice(1, 5), correct: Number(p[5]) };
}

// gap-тест из примера: цель → ___; цели нет в тексте → null (безопасно)
function gapTest(target, cleanText, distr, k) {
  if (!target || !cleanText || !cleanText.includes(target)) return null;
  return Object.assign(mix(target, distr, k), { q: cleanText.replace(target, '___') });
}

// gap-тест по вхождению front (без учёта регистра), исключая указанный пример
function frontGap(examples, front, distr, k, excludeText) {
  const f = front.toLowerCase();
  for (const e of examples) {
    if (e.text === excludeText) continue;
    const at = e.text.toLowerCase().indexOf(f);
    if (at >= 0) {
      const q = e.text.slice(0, at) + '___' + e.text.slice(at + f.length);
      return Object.assign(mix(front, distr, k), { q });
    }
  }
  return null;
}

